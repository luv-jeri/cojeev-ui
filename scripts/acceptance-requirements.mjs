/**
 * Turn the component inventory into the Phase 0 exit artefact: what each entry
 * still needs before it can have an acceptance row.
 *
 * ROADMAP-TO-10.md requires "every inventory entry has an acceptance row; no
 * unresolved acceptance-blocking finding". This computes the gap per entry and
 * groups it so Phase 2 can be batched rather than attacked component by component.
 *
 * Read-only. Reads docs/workspace/baseline/inventory.json.
 *
 *   node scripts/acceptance-requirements.mjs [--md=PATH] [--json=PATH]
 */
import fs from "node:fs";

const args = new Map(process.argv.slice(2).map(a => { const [k, ...v] = a.split("="); return [k, v.join("=") || true]; }));
const mdOut = args.get("--md") || "docs/workspace/ACCEPTANCE-GAPS.md";
const jsonOut = args.get("--json") || "docs/workspace/baseline/acceptance-gaps.json";

const inv = JSON.parse(fs.readFileSync("docs/workspace/baseline/inventory.json", "utf8"));
const rows = inv.rows;

/** What a single entry needs, and why. Ordered cheapest-first. */
const needsFor = r => {
  const needs = [];
  if (!r.contract) needs.push({ gap: "no-contract", why: "no written contract: appearance is undefined, so no visual acceptance is possible" });
  if (r.fixturesPresent === 0) needs.push({ gap: "no-fixture", why: "no reference fixture: the visual gate can never judge this entry" });
  if (r.unitTests.length === 0) needs.push({ gap: "no-unit-test", why: "no unit test names this entry" });
  if (r.browserTests.length === 0) needs.push({ gap: "no-browser-gate", why: "no browser gate names this entry: no rendered behaviour is verified" });
  if (!r.docsPage) needs.push({ gap: "not-in-docs-catalog", why: "not exposed by the documentation catalog" });
  if (r.examples.length === 0) needs.push({ gap: "no-worked-example", why: "no worked example in the docs site" });
  return needs;
};

for (const r of rows) r.needs = needsFor(r);

/** Acceptance tier: how close an entry is to a defensible acceptance row. */
const tierOf = r => {
  const hasVisual = r.fixturesPresent > 0 && r.contract;
  const hasBehaviour = r.browserTests.length > 0;
  const hasUnit = r.unitTests.length > 0;
  if (hasVisual && hasBehaviour && hasUnit) return "complete";
  if (hasVisual && hasBehaviour) return "visual+behaviour";
  if (hasVisual) return "visual-only";
  if (hasBehaviour || hasUnit) return "behaviour-only";
  return "unverified";
};
for (const r of rows) r.acceptanceTier = tierOf(r);

const byTier = {};
for (const r of rows) (byTier[r.acceptanceTier] ??= []).push(r.id);
const gapCounts = {};
for (const r of rows) for (const n of r.needs) gapCounts[n.gap] = (gapCounts[n.gap] || 0) + 1;

const branch = rows.filter(r => r.tier === "base");
const other = rows.filter(r => r.tier !== "base");

const summary = {
  entries: rows.length,
  acceptanceTiers: Object.fromEntries(Object.entries(byTier).map(([k, v]) => [k, v.length])),
  gaps: gapCounts,
  complete: byTier.complete?.length ?? 0,
  baseTier: {
    total: branch.length,
    needsBrowserGate: branch.filter(r => r.browserTests.length === 0).length,
    needsUnitTest: branch.filter(r => r.unitTests.length === 0).length,
  },
  additionalTier: {
    total: other.length,
    needContractAndFixture: other.filter(r => !r.contract).length,
    haveBehaviour: other.filter(r => r.browserTests.length || r.unitTests.length).length,
  },
};

fs.mkdirSync("docs/workspace/baseline", { recursive: true });
fs.writeFileSync(jsonOut, JSON.stringify({ summary, entries: rows.map(r => ({ id: r.id, tier: r.tier, acceptanceTier: r.acceptanceTier, gaps: r.needs.map(n => n.gap) })) }, null, 2));

const list = a => a.length ? a.join(", ") : "(none)";
const md = `# Acceptance gaps — what every entry still needs

Generated by \`node scripts/acceptance-requirements.mjs\` from
\`baseline/inventory.json\`. Do not hand-edit.

Phase 0 exit criterion: *"every inventory entry has an acceptance row; no unresolved
acceptance-blocking finding."* This is the distance to that.

## Acceptance tier of each entry

| tier | meaning | entries |
| --- | --- | ---: |
| **complete** | visual spec + browser gate + unit test | ${summary.acceptanceTiers.complete ?? 0} |
| **visual+behaviour** | has a contract and fixtures, and a browser gate, but no unit test | ${summary.acceptanceTiers["visual+behaviour"] ?? 0} |
| **visual-only** | has a contract and fixtures, but no behavioural gate at all | ${summary.acceptanceTiers["visual-only"] ?? 0} |
| **behaviour-only** | behaviour is tested, but no contract or fixture exists | ${summary.acceptanceTiers["behaviour-only"] ?? 0} |
| **unverified** | neither a visual spec nor a behavioural gate | ${summary.acceptanceTiers.unverified ?? 0} |

## The gaps, counted

| gap | entries affected |
| --- | ---: |
${Object.entries(gapCounts).sort((a, b) => b[1] - a[1]).map(([k, v]) => `| \`${k}\` | ${v} |`).join("\n")}

## Wave 1 — base tier: components that already have a visual spec but no behavioural gate

These are the **cheapest real wins**: the design contract already exists, so the work is
adding a browser gate, not deciding what the component should look like.

${summary.baseTier.needsBrowserGate} of ${summary.baseTier.total} base-tier entries have no browser gate:
${list(branch.filter(r => r.browserTests.length === 0).map(r => `\`${r.id}\``))}

${summary.baseTier.needsUnitTest} of ${summary.baseTier.total} have no unit test:
${list(branch.filter(r => r.unitTests.length === 0).map(r => `\`${r.id}\``))}

## Wave 2 — additional tier: components with no design reference at all

${summary.additionalTier.total} entries, of which **${summary.additionalTier.needContractAndFixture} have no contract and no
fixture**. These cannot be made visually acceptable by writing code: they need an owner-approved
**rendered contract** first. ${summary.additionalTier.haveBehaviour} of them already have some
behavioural evidence, which is the only acceptance they have today.

Do not open these as component tickets. Open them as a single scoping decision: which of the
${summary.additionalTier.total} are meant to be visually verified at all, and who approves the reference?

## Entries fully complete (${summary.complete})

${list(byTier.complete ?? [])}

## Per-entry detail

| entry | tier | acceptance tier | gaps |
| --- | --- | --- | --- |
${rows.slice().sort((a, b) => a.id.localeCompare(b.id)).map(r => `| \`${r.id}\` | ${r.tier} | ${r.acceptanceTier} | ${r.needs.map(n => n.gap).join(", ") || "—"} |`).join("\n")}
`;
fs.writeFileSync(mdOut, md);
console.log(JSON.stringify(summary, null, 2));
console.log(`\nwrote ${mdOut} and ${jsonOut}`);
