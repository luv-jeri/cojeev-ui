/**
 * Build-time specimen API extraction for the assembly's Source chapter.
 *
 * Chapter 05 claims that every object on the bench has a source. To make that
 * claim factual it has to show the selected component's own public API, read
 * from the component the registry actually ships — not a site-invented stand-in.
 * The visitor selects a specimen in one chapter and reads its API in another, so
 * the data has to be present synchronously in the client bundle: it is written
 * out here, at build time, as a static module the page imports directly.
 *
 * The parsing itself lives in `scripts/component-api.mjs` and is shared with
 * `tests/component-api.test.ts`; this script only serialises its result.
 *
 * Regenerate with:
 *
 *   npm run specimens:api
 *
 * `tests/component-api.test.ts` fails if the committed data drifts from what the
 * extractor reads now.
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { componentAPIs } from "./component-api.mjs";
import { SPECIMEN_TRAYS } from "../components/landing/assembly/canonical.ts";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const output = path.join(root, "components/landing/assembly/specimen-api.generated.ts");

const ids = SPECIMEN_TRAYS.map((tray) => tray.id);
const apis = componentAPIs(ids);

const banner = `/**
 * Generated by scripts/generate-specimen-api.mjs — do not edit by hand.
 *
 * The public prop surface of every specimen on the assembly bench, read from
 * \`registry/cojeev/ui/<id>.tsx\` with the TypeScript compiler. Regenerate with
 * \`npm run specimens:api\`; tests/component-api.test.ts guards it against drift.
 */

/** One authored prop of an exported props type. */
export type SpecimenApiProp = {
  readonly name: string;
  readonly type: string;
  readonly required: boolean;
  readonly description: string;
};

/** One exported props type of a specimen component. */
export type SpecimenApiDeclaration = {
  readonly name: string;
  readonly props: readonly SpecimenApiProp[];
};

/** Keyed by registry component id, in the order the types are declared. */
export const SPECIMEN_API: Record<string, readonly SpecimenApiDeclaration[]> = `;

writeFileSync(output, `${banner}${JSON.stringify(apis, null, 2)};\n`);
console.log(`Wrote ${path.relative(root, output)} for ${ids.length} specimens: ${ids.join(", ")}`);
